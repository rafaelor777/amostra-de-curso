/* =====================================================
   MOEDA
===================================================== */

function moeda(valor) {

  return Number(valor).toLocaleString(
    "pt-BR",
    {
      style: "currency",
      currency: "BRL"
    }
  );

}


/* =====================================================
   ESCAPE HTML
===================================================== */

function escapeHTML(texto) {

  return String(texto)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");

}


/* =====================================================
   MOSTRAR PRODUTOS
===================================================== */

function mostrar(lista = listaAtual) {

  const container =
    document.getElementById("produtos");

  if (!container) return;


  listaAtual = lista;


  if (lista.length === 0) {

    container.innerHTML = `
      <div class="empty-message">

        <h3>
          Nenhum produto encontrado
        </h3>

        <p>
          Tente outra categoria ou pesquisa.
        </p>

      </div>
    `;

    return;
  }


  container.innerHTML =
    lista.map(produto => {

      const favorito =
        favoritos.includes(produto.id);

      const temOferta =
        produto.precoOferta !== undefined &&
        produto.precoOferta < produto.preco;


      const imagem =
        produto.imagem ||
        "";


      return `

        <article class="product-card">

          ${
            temOferta
              ? `<span class="badge-discount">
                  🔥 OFERTA
                 </span>`
              : ""
          }


          <button
            class="favorite-btn ${favorito ? "active" : ""}"
            onclick="alternarFavorito(${produto.id})"
            title="Favoritar"
          >
            ${favorito ? "❤️" : "♡"}
          </button>


          <div class="product-img-wrapper">

            <img
              src="${imagem}"
              alt="${escapeHTML(produto.nome)}"
              onerror="
                this.onerror=null;
                this.src='data:image/svg+xml;charset=UTF-8,${encodeURIComponent(`
                  <svg xmlns="http://www.w3.org/2000/svg" width="300" height="200">
                    <rect width="100%" height="100%" fill="#f1f5f9"/>
                    <text x="50%" y="50%"
                      dominant-baseline="middle"
                      text-anchor="middle"
                      font-family="Arial"
                      font-size="18"
                      fill="#64748b">
                      Imagem indisponível
                    </text>
                  </svg>
                `)}'
              "
            >

          </div>


          <div class="product-title">
            ${escapeHTML(produto.nome)}
          </div>


          <div class="product-unit">
            ${escapeHTML(produto.cat)}
          </div>


          <div class="price-container">

            ${
              temOferta
                ? `
                  <div class="old-price">
                    ${moeda(produto.preco)}
                  </div>

                  <div class="current-price">
                    ${moeda(produto.precoOferta)}
                  </div>
                `
                : `
                  <div class="current-price">
                    ${moeda(produto.preco)}
                  </div>
                `
            }

          </div>


          <button
            class="add-cart-btn"
            onclick="adicionarCarrinho(${produto.id})"
          >
            🛒 Adicionar
          </button>

        </article>

      `;

    }).join("");

}


/* =====================================================
   FILTRAR
===================================================== */

function filtrar(cat) {

  if (cat === "Todos") {

    listaAtual = [...produtos];

    atualizarTitulo("🛍️ Todos os produtos");

  }

  else if (cat === "Ofertas") {

    listaAtual =
      produtos.filter(
        produto =>
          produto.precoOferta !== undefined
      );

    atualizarTitulo("🔥 Ofertas");

  }

  else {

    listaAtual =
      produtos.filter(
        produto =>
          produto.cat === cat
      );

    atualizarTitulo(`🛍️ ${cat}`);

  }


  mostrar(listaAtual);

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

}


/* =====================================================
   TÍTULO
===================================================== */

function atualizarTitulo(texto) {

  const titulo =
    document.getElementById("tituloProdutos");

  if (titulo) {
    titulo.textContent = texto;
  }

}


/* =====================================================
   BUSCA
===================================================== */

function buscar() {

  const campo =
    document.getElementById("busca");

  if (!campo) return;


  const termo =
    campo.value
      .trim()
      .toLowerCase();


  if (!termo) {

    filtrar("Todos");

    return;

  }


  const resultado =
    produtos.filter(produto =>

      produto.nome
        .toLowerCase()
        .includes(termo)

      ||

      produto.cat
        .toLowerCase()
        .includes(termo)

    );


  atualizarTitulo(
    `🔎 Resultados para "${campo.value}"`
  );


  mostrar(resultado);

}


/* =====================================================
   CARRINHO
===================================================== */

function salvarCarrinho() {

  localStorage.setItem(
    "carrinhoMercado",
    JSON.stringify(carrinho)
  );

}


function atualizarContador() {

  const contador =
    document.getElementById("contador");

  if (!contador) return;


  const quantidade =
    carrinho.reduce(
      (total, item) =>
        total + item.quantidade,
      0
    );


  contador.textContent =
    quantidade;

}


/* =====================================================
   ADICIONAR AO CARRINHO
===================================================== */

function adicionarCarrinho(id) {

  const produto =
    produtos.find(
      item => item.id === id
    );


  if (!produto) return;


  const itemExistente =
    carrinho.find(
      item => item.id === id
    );


  if (itemExistente) {

    itemExistente.quantidade++;

  }

  else {

    carrinho.push({

      id: produto.id,

      nome: produto.nome,

      preco:
        produto.precoOferta ??
        produto.preco,

      imagem: produto.imagem,

      quantidade: 1

    });

  }


  salvarCarrinho();

  atualizarContador();

  renderCarrinho();

  mostrarToast(
    `${produto.nome} foi adicionado ao carrinho!`
  );

}


/* =====================================================
   REMOVER
===================================================== */

function removerCarrinho(id) {

  carrinho =
    carrinho.filter(
      item => item.id !== id
    );


  salvarCarrinho();

  atualizarContador();

  renderCarrinho();

}


/* =====================================================
   ALTERAR QUANTIDADE
===================================================== */

function alterarQuantidade(id, quantidade) {

  const item =
    carrinho.find(
      produto => produto.id === id
    );


  if (!item) return;


  item.quantidade =
    Math.max(
      1,
      quantidade
    );


  salvarCarrinho();

  atualizarContador();

  renderCarrinho();

}


/* =====================================================
   RENDERIZAR CARRINHO
===================================================== */

function renderCarrinho() {

  const container =
    document.getElementById("itensCarrinho");

  const totalElement =
    document.getElementById("total");


  if (!container || !totalElement)
    return;


  if (carrinho.length === 0) {

    container.innerHTML = `
      <div class="empty-message">

        <h3>
          Seu carrinho está vazio
        </h3>

        <p>
          Adicione alguns produtos!
        </p>

      </div>
    `;

    totalElement.textContent =
      moeda(0);

    return;

  }


  let total = 0;


  container.innerHTML =
    carrinho.map(item => {

      const subtotal =
        item.preco *
        item.quantidade;


      total += subtotal;


      return `

        <div class="cart-item">

          <img
            class="cart-item-image"
            src="${item.imagem}"
            alt="${escapeHTML(item.nome)}"
          >

          <div class="cart-item-info">

            <div class="cart-item-name">
              ${escapeHTML(item.nome)}
            </div>

            <div class="cart-item-price">
              ${moeda(item.preco)}
            </div>

          </div>


          <div class="quantity-controls">

            <button
              onclick="
                alterarQuantidade(
                  ${item.id},
                  ${item.quantidade - 1}
                )
              "
            >
              −
            </button>

            <strong>
              ${item.quantidade}
            </strong>

            <button
              onclick="
                alterarQuantidade(
                  ${item.id},
                  ${item.quantidade + 1}
                )
              "
            >
              +
            </button>

          </div>


          <button
            class="remove-item"
            onclick="removerCarrinho(${item.id})"
            title="Remover"
          >
            🗑️
          </button>

        </div>

      `;

    }).join("");


  totalElement.textContent =
    moeda(total);

}



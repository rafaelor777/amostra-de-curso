/* =====================================================
   ENVIAR AVALIAÇÃO
===================================================== */

function enviarAvaliacao() {

  /* PEGA O USUÁRIO QUE ESTÁ LOGADO */

  const usuario =
    JSON.parse(
      localStorage.getItem(
        "usuarioMercado"
      ) || "null"
    );


  /* VERIFICA SE ESTÁ LOGADO */

  if (!usuario) {

    alert(
      "Você precisa estar logado para fazer uma avaliação."
    );

    abrirLogin();

    return;

  }


  /* VERIFICA AS ESTRELAS */

  if (notaSelecionada === 0) {

    alert(
      "Escolha uma quantidade de estrelas."
    );

    return;

  }


  const campo =
    document.getElementById(
      "comentarioAvaliacao"
    );


  const comentario =
    campo
      ? campo.value.trim()
      : "";


  /* CRIA A AVALIAÇÃO */

  const novaAvaliacao = {

    id: Date.now(),

    nome: usuario.nome,

    nota: notaSelecionada,

    comentario:
      comentario ||
      "Sem comentário.",

    data:
      new Date().toLocaleDateString(
        "pt-BR"
      )

  };


  /* SALVA */

  avaliacoes.unshift(
    novaAvaliacao
  );


  localStorage.setItem(
    "avaliacoesMercado",
    JSON.stringify(
      avaliacoes
    )
  );


  /* LIMPA O FORMULÁRIO */

  if (campo) {

    campo.value = "";

  }


  notaSelecionada = 0;

  atualizarEstrelas();

  mostrarAvaliacoes();


  mostrarToast(
    "⭐ Avaliação enviada com sucesso!"
  );

}



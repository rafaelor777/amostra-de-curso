function obterOfertas() {

  return produtos.filter(produto =>
    produto.precoOferta !== undefined &&
    produto.precoOferta < produto.preco
  );

}


/* =====================================================
   INICIAR CARROSSEL
===================================================== */

function iniciarCarrosselOfertas() {

  const track =
    document.getElementById("ofertasTrack");

  const dots =
    document.getElementById("ofertasDots");

  if (!track || !dots) return;


  const ofertas = obterOfertas();


  if (ofertas.length === 0) {

    track.innerHTML = `
      <div class="oferta-vazia">
        Nenhuma oferta disponível.
      </div>
    `;

    return;
  }


  ofertaAtual = 0;

  track.innerHTML =
    ofertas.map((produto, index) => {

      return `

        <div class="oferta-slide">

          <div class="oferta-imagem">

            <img
              src="${produto.imagem}"
              alt="${escapeHTML(produto.nome)}"
              onerror="
                this.onerror=null;
                this.style.display='none';
              "
            >

          </div>


          <div class="oferta-info">

            <span class="oferta-tag">
              🔥 OFERTA
            </span>


            <h2>
              ${escapeHTML(produto.nome)}
            </h2>


            <p class="oferta-categoria">
              ${escapeHTML(produto.cat)}
            </p>


            <div class="oferta-precos">

              <span class="oferta-preco-antigo">
                ${moeda(produto.preco)}
              </span>

              <span class="oferta-preco-novo">
                ${moeda(produto.precoOferta)}
              </span>

            </div>


            <button
              class="oferta-carrinho"
              onclick="adicionarCarrinho(${produto.id})"
            >
              🛒 Adicionar ao carrinho
            </button>

          </div>

        </div>

      `;

    }).join("");


  /* CRIAR BOLINHAS */

  dots.innerHTML = "";

  ofertas.forEach((produto, index) => {

    const dot =
      document.createElement("button");

    dot.className = "oferta-dot";

    dot.type = "button";

    dot.setAttribute(
      "aria-label",
      `Ver oferta ${index + 1}`
    );


    dot.addEventListener(
      "click",
      () => irParaOferta(index)
    );


    dots.appendChild(dot);

  });


  atualizarOferta();

  iniciarIntervaloOfertas();

}


/* =====================================================
   ATUALIZAR OFERTA
===================================================== */

function atualizarOferta() {

  const track =
    document.getElementById("ofertasTrack");

  const slides =
    document.querySelectorAll(".oferta-slide");

  const dots =
    document.querySelectorAll(".oferta-dot");


  if (!track || slides.length === 0) return;


  track.style.transform =
    `translateX(-${ofertaAtual * 100}%)`;


  dots.forEach((dot, index) => {

    dot.classList.toggle(
      "active",
      index === ofertaAtual
    );

  });

}


/* =====================================================
   PRÓXIMA OFERTA
===================================================== */

function moverOferta(direcao) {

  const ofertas =
    obterOfertas();


  if (ofertas.length === 0) return;


  ofertaAtual += direcao;


  if (ofertaAtual >= ofertas.length) {

    ofertaAtual = 0;

  }


  if (ofertaAtual < 0) {

    ofertaAtual =
      ofertas.length - 1;

  }


  atualizarOferta();

  iniciarIntervaloOfertas();

}


/* =====================================================
   IR PARA UMA OFERTA
===================================================== */

function irParaOferta(indice) {

  const ofertas =
    obterOfertas();


  if (
    indice < 0 ||
    indice >= ofertas.length
  ) {
    return;
  }


  ofertaAtual = indice;

  atualizarOferta();

  iniciarIntervaloOfertas();

}


/* =====================================================
   TROCA AUTOMÁTICA
===================================================== */

function iniciarIntervaloOfertas() {

  clearInterval(ofertaIntervalo);


  ofertaIntervalo =
    setInterval(() => {

      moverOferta(1);

    }, 4500);

}


